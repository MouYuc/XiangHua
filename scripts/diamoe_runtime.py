"""Shared DiaMoE-TTS runtime for dialect synthesis.

Three things are centralised here because both the single-shot CLI
(``infer_diamoe_lora.py``) and the dialect baseline sweep need them:

* how an IPA row becomes model text, and which tokens the vocabulary drops;
* how the frozen base checkpoint (plus an optional speaker adapter) is built;
* how the MoE gate is observed while sampling, so dialect routing can be audited.

The base checkpoint ships without the ``dialect_classifier`` tensors and the
released backbone config has no LoRA layers, so the model is always assembled
here and the state dicts are loaded with ``strict=False`` in two stages.
"""

from __future__ import annotations

import contextlib
import io
import sys
from pathlib import Path

import torch

DEFAULT_ROOT = Path("third_party/DiaMoE-TTS")
DEFAULT_BASE_CKPT = "checkpoints/10ep_mlpEXP_9.pt"
DEFAULT_VOCODER = "checkpoints/vocos-mel-24khz"

# Cached frontend-IPA to model-IPA normalisation table; loaded on first use.
_REMAP_CACHE: dict[str, str] | None = None


def ensure_import_path(root: Path) -> Path:
    """Put the vendored ``f5_tts`` package on sys.path and return the source root."""
    src_root = Path(root).resolve() / "diamoe_tts" / "src"
    if str(src_root) not in sys.path:
        sys.path.insert(0, str(src_root))
    return src_root


def load_symbol_tables(root: Path = DEFAULT_ROOT) -> tuple[set[str], set[str]]:
    """Return (ipa_symbols, punctuation) as the model expects them, bracket-wrapped."""
    root = Path(root)
    vocab_lines = (root / "diamoe_tts/data/vocab.txt").read_text(encoding="utf-8").splitlines()
    ipa_set = {line for line in vocab_lines if line.startswith("[") and line.endswith("]")}
    punctuation = set((root / "diamoe_tts/data/punctuation.txt").read_text(encoding="utf-8").splitlines())
    return ipa_set, punctuation


def read_ipa_row(path: str | Path, line_index: int = 0) -> tuple[str, str, str]:
    """Return (row_id, plain_text, raw_ipa) for one row of an id/text/ipa file."""
    rows = [row for row in Path(path).read_text(encoding="utf-8").splitlines() if row.strip()]
    if line_index >= len(rows):
        raise SystemExit(f"{path} has {len(rows)} rows, index {line_index} is out of range")
    parts = rows[line_index].split("\t")
    if len(parts) < 3:
        raise SystemExit(f"{path} row {line_index} is not id/text/ipa")
    return parts[0], parts[1], parts[2]


def load_vocab_remap(path: str | Path | None = None) -> dict[str, str]:
    """Return the frontend-IPA to model-IPA normalisation table.

    The DiaMoE frontend and the released acoustic model disagree about 64 IPA
    tokens (see ``docs/DIALECT_LEXICON_DEFECTS.md``). The table that repairs the
    disagreement is generated by ``scripts/ipa_vocab_normalize.py`` and stored as
    data, so every mapping stays reviewable instead of being re-derived here.

    A missing table is deliberately not fatal: callers then behave exactly as they
    did before normalisation existed, and ``frontend_lexicon_audit.py`` is what
    reports the resulting losses.
    """
    global _REMAP_CACHE
    if path is not None:
        from ipa_vocab_normalize import load_remap

        return load_remap(Path(path))
    if _REMAP_CACHE is None:
        try:
            from ipa_vocab_normalize import DEFAULT_REMAP, load_remap

            _REMAP_CACHE = load_remap(DEFAULT_REMAP)
        except Exception:
            _REMAP_CACHE = {}
    return _REMAP_CACHE


def ipa_to_model_text(
    raw_ipa: str,
    ipa_set: set[str],
    punctuation: set[str],
    remap: dict[str, str] | None = None,
    return_trace: bool = False,
) -> tuple:
    """Convert a raw IPA row into model text.

    Returns (model_text, kept_tokens, dropped_tokens), or a 4-tuple carrying the
    normalisation trace when ``return_trace`` is set. A dropped token means the
    frontend produced a phone the acoustic model has no embedding for, so that
    phone silently disappears from the utterance.

    Tokens are normalised into the model vocabulary before the lookup. Without
    that step the 64 disagreeing tokens - whole syllable families among them -
    are dropped without any error, which is what made characters vanish from the
    synthesised audio.
    """
    tokens = raw_ipa.split()
    if remap is None:
        remap = load_vocab_remap()

    trace: list[dict[str, str]] = []
    try:
        from ipa_vocab_normalize import normalize_for_model

        # The normaliser works on bare symbols; ipa_set is bracket-wrapped. It
        # also aliases the pause-carrying punctuation the model's tables lack
        # (``；`` and ``：``), which would otherwise be dropped before the
        # tokenizer ever saw them.
        bare_vocabulary = {symbol[1:-1] for symbol in ipa_set}
        tokens, trace = normalize_for_model(tokens, bare_vocabulary, remap)
    except Exception:
        # Normalisation is an improvement, not a requirement: if the helper is
        # unavailable the original tokens are used, and any remaining loss still
        # shows up in dropped_tokens.
        pass

    kept: list[str] = []
    dropped: list[str] = []
    for token in tokens:
        symbol = f"[{token}]"
        if symbol in ipa_set:
            kept.append(symbol)
        elif symbol in punctuation:
            kept.append(token)
        elif token == "|":
            continue
        else:
            dropped.append(token)
    text = " ".join(kept)
    if return_trace:
        return text, kept, dropped, trace
    return text, kept, dropped


class GateRecorder:
    """Collect MoE gate logits for every sampling step.

    ``MoeLayer.forward`` pools the target text (reference tokens are masked out)
    and selects the top-k experts, so these logits answer "which dialect expert
    does this text route to?" independently of the reference timbre.
    """

    def __init__(self, model):
        self.model = model
        self.logits: list[torch.Tensor] = []
        self._handle = None

    def __enter__(self) -> "GateRecorder":
        self._handle = self.model.transformer.moe.gate.register_forward_hook(self._record)
        return self

    def __exit__(self, *exc) -> bool:
        if self._handle is not None:
            self._handle.remove()
            self._handle = None
        return False

    def _record(self, module, inputs, output) -> None:
        self.logits.append(output.detach().to(torch.float32).cpu())

    def summary(self) -> dict:
        if not self.logits:
            return {"calls": 0}
        rows = torch.cat([logit.reshape(-1, logit.shape[-1]) for logit in self.logits], dim=0)
        per_step = [int(row.argmax().item()) for row in rows]
        probs = torch.softmax(rows, dim=-1)
        mean = probs.mean(dim=0)
        top1 = int(mean.argmax().item())
        entropy = float(-(mean * torch.log(mean + 1e-9)).sum().item())
        return {
            "calls": len(self.logits),
            "num_experts": int(mean.shape[-1]),
            "top1_expert": top1,
            "top1_prob": round(float(mean[top1]), 6),
            "entropy": round(entropy, 6),
            "expert_mean_prob": [round(float(value), 6) for value in mean],
            "top1_per_call": per_step,
            "top1_agreement": round(per_step.count(max(set(per_step), key=per_step.count)) / len(per_step), 4),
        }


def build_model(
    root: str | Path = DEFAULT_ROOT,
    base_ckpt: str | None = DEFAULT_BASE_CKPT,
    lora_path: str | Path | None = None,
    lora_scale: float = 1.0,
    device: str | None = None,
) -> dict:
    """Assemble the DiaMoE model and load the base checkpoint plus optional adapter."""
    root = Path(root).resolve()
    src_root = ensure_import_path(root)
    device = device or ("cuda" if torch.cuda.is_available() else "cpu")

    from omegaconf import OmegaConf
    from hydra.utils import get_class
    from f5_tts.infer.utils_infer import load_vocoder
    from f5_tts.model import CFM
    from f5_tts.model.moe import EXPERT_DICT, MoeLayer, SimpleGate
    from f5_tts.model.utils import get_tokenizer

    vocab_path = root / "diamoe_tts/data/vocab.txt"
    vocab_char_map, vocab_size = get_tokenizer(str(vocab_path), "custom")

    vocoder = load_vocoder(
        vocoder_name="vocos",
        is_local=True,
        local_path=str(root / DEFAULT_VOCODER),
        device=device,
    )

    base_ckpt_path = (root / (base_ckpt or DEFAULT_BASE_CKPT)).resolve()
    lora_ckpt = Path(lora_path).resolve() if lora_path else None

    backbone_config = "diamoetts_peft.yaml" if lora_ckpt else "diamoetts.yaml"
    cfg = OmegaConf.load(src_root / "f5_tts" / "configs" / backbone_config)

    expert_cls = EXPERT_DICT[cfg.MoE.expert_type.lower()]
    experts = [expert_cls() for _ in range(cfg.MoE.num_exps)]
    moe = MoeLayer(
        experts=experts,
        gate=SimpleGate(cfg.MoE.num_exps),
        num_experts=cfg.MoE.num_exps,
        num_experts_per_tok=cfg.MoE.moe_topK,
        use_residual=True,
        use_dialect_clf=cfg.MoE.use_dialect_clf,
        dialect_clf_lambda=cfg.MoE.dialect_clf_lambda,
        dialect_kinds=cfg.MoE.dialect_kinds,
    )
    model_cls = get_class(f"f5_tts.model.{cfg.model.backbone}")
    model = CFM(
        transformer=model_cls(
            **cfg.model.arch,
            text_num_embeds=vocab_size,
            mel_dim=cfg.model.mel_spec.n_mel_channels,
            moe=moe,
        ),
        mel_spec_kwargs=cfg.model.mel_spec,
        vocab_char_map=vocab_char_map,
        use_moe=cfg.MoE.use_moe,
    ).to(device)

    checkpoint = torch.load(base_ckpt_path, map_location="cpu", weights_only=True)
    base_state = dict(checkpoint["model_state_dict"])
    for key in (
        "transformer.moe.dialect_classifier.weight",
        "transformer.moe.dialect_classifier.bias",
    ):
        base_state.pop(key, None)
    base_missing, base_unexpected = model.load_state_dict(base_state, strict=False)

    adapter_report = None
    if lora_ckpt is not None:
        adapter = torch.load(lora_ckpt, map_location="cpu", weights_only=True)
        state = adapter["model_state_dict"]
        # lora_B is zero-initialised, so scaling it scales the adapter linearly.
        if lora_scale != 1.0:
            state = {
                key: (value * lora_scale if key.endswith("lora_B") else value)
                for key, value in state.items()
            }
        adapter_missing, adapter_unexpected = model.load_state_dict(state, strict=False)
        adapter_report = {
            "path": str(lora_ckpt),
            "scale": lora_scale,
            "missing_keys": len(adapter_missing),
            "unexpected_keys": len(adapter_unexpected),
        }

    model.eval()
    return {
        "root": root,
        "src_root": src_root,
        "device": device,
        "model": model,
        "vocoder": vocoder,
        "cfg": cfg,
        "backbone_config": backbone_config,
        "vocab_char_map": vocab_char_map,
        "vocab_size": vocab_size,
        "base_ckpt": str(base_ckpt_path),
        "base_load": {"missing_keys": len(base_missing), "unexpected_keys": len(base_unexpected)},
        "adapter": adapter_report,
    }


def prepare_reference(ref_audio: str | Path, ref_text: str):
    """Trim silence from the reference clip and return the processed pair."""
    from f5_tts.infer.utils_infer import preprocess_ref_audio_text

    return preprocess_ref_audio_text(str(ref_audio), ref_text)


def squeeze_reference_silence(
    ref_audio,
    target_rate: int = 24000,
    min_gap_seconds: float = 0.25,
    replacement_gap_seconds: float = 0.06,
    top_db: int = 32,
):
    """Remove long internal pauses from a reference clip.

    F5 continues the reference's prosody, including its silences. A reference
    that pauses for a second mid-clip makes the generated line pause there too,
    and because the total mel budget is fixed, that pause is paid for by
    squeezing the syllables either side of it. Only gaps longer than
    ``min_gap_seconds`` are touched, so ordinary inter-syllable spacing survives.
    """
    import librosa
    import numpy as np

    if isinstance(ref_audio, (str, Path)):
        audio, rate = librosa.load(str(ref_audio), sr=target_rate, mono=True)
    else:
        audio = np.asarray(ref_audio, dtype=np.float32).reshape(-1)
        rate = target_rate

    spans = librosa.effects.split(audio, top_db=top_db)
    if len(spans) <= 1:
        return audio, rate

    pieces = []
    cursor = 0
    for start, end in spans:
        gap = start - cursor
        if cursor == 0:
            pieces.append(audio[start:end])
        elif gap >= int(min_gap_seconds * rate):
            pieces.append(np.zeros(int(replacement_gap_seconds * rate), dtype=audio.dtype))
            pieces.append(audio[start:end])
        else:
            pieces.append(audio[cursor:end])
        cursor = end
    squeezed = np.concatenate(pieces) if pieces else audio
    if len(audio) - len(squeezed) < int(0.15 * rate):
        return audio, rate
    return squeezed, rate


def synthesize(
    runtime: dict,
    ref_audio,
    ref_text: str,
    gen_text: str,
    *,
    seed: int = 333,
    nfe: int = 32,
    cfg_strength: float = 2.0,
    speed: float = 1.0,
    capture_gate: bool = False,
    quiet: bool = True,
    fix_duration: float | None = None,
):
    """Run one inference. Returns (audio, sample_rate, gate_summary_or_None).

    ``fix_duration`` is the total mel duration in seconds, reference included.
    Pass it to take pacing out of the reference clip's hands: by default F5
    derives the output length from how many tokens the reference covers, so a
    short reference makes the generated dialect line race, and a long one drags.
    """
    from f5_tts.infer.utils_infer import infer_process

    torch.manual_seed(seed)
    recorder = GateRecorder(runtime["model"]) if capture_gate else None
    sink = io.StringIO() if quiet else None
    with contextlib.redirect_stdout(sink) if sink is not None else contextlib.nullcontext():
        if recorder is not None:
            recorder.__enter__()
        try:
            audio, sample_rate, _ = infer_process(
                ref_audio,
                ref_text,
                gen_text,
                runtime["model"],
                runtime["vocoder"],
                mel_spec_type="vocos",
                target_rms=0.1,
                cross_fade_duration=0.15,
                nfe_step=nfe,
                cfg_strength=cfg_strength,
                sway_sampling_coef=-1.0,
                speed=speed,
                fix_duration=fix_duration,
                device=runtime["device"],
            )
        finally:
            if recorder is not None:
                recorder.__exit__(None, None, None)
    return audio, sample_rate, (recorder.summary() if recorder is not None else None)